namespace Chernika.Web;

/// <summary>
/// Маркер точки входа <c>Chernika.Web</c> для тестового хоста.
/// <para>
/// Top-level statements из <c>Program.cs</c> компилируются во внутренний класс
/// <c>Program</c> в глобальном пространстве имён, на который нельзя сослаться из
/// другого проекта. Добавлять пространство имён в сам <c>Program.cs</c> нельзя:
/// Razor-компоненты разрешают <c>Shared</c>, <c>Components</c> и <c>Auth</c>
/// относительно пространства файла, и объявлениеnamespace ломает их все.
/// </para>
/// <para>
/// Поэтому маркер вынесен отдельным файлом и ничего не меняет в самом хосте.
/// <c>WebApplicationFactory</c> использует сборку типа-записи, чтобы найти
/// корень содержимого и зависимости, — сам тип при этом не создаётся. Этого
/// достаточно, чтобы поднять НАСТОЯЩИй хост и проверить, что worker обработки
/// сроков зарегистрирован в нём ровно один.
/// </para>
/// </summary>
public sealed class EntryPointMarker;
