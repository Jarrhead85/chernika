namespace Chernika.Web.Pages.Structure;

/// <summary>
/// Состояние загрузки карты в редакторе.
/// <para>
/// Это состояние представления, а НЕ статус ХК: карта может быть в статусе
/// «Черновик» и при этом не загружаться вовсе.
/// </para>
/// <para>
/// Различаются пять состояний, потому что требуют разных действий:
/// загрузка ещё идёт, карта готова, загрузка упала, карты нет и доступа
/// нет. Смешивать «нет доступа» с «техническая ошибка» нельзя: пользователь
/// получает ложное объяснение отказа.
/// </para>
/// </summary>
public enum HkEditLoadState
{
    /// <summary>Обязательные данные читаются.</summary>
    Loading,

    /// <summary>Карта загружена, редактор доступен.</summary>
    Ready,

    /// <summary>Загрузка упала: показано сообщение и предложен повтор.</summary>
    Error,

    /// <summary>Карты не существует.</summary>
    NotFound,

    /// <summary>Карта существует, но пользователь не имеет к ней доступа.</summary>
    Forbidden
}