namespace Chernika.Infrastructure.Services;

/// <summary>
/// Настройки обработки сроков действия химмотологических карт.
/// <para>
/// <see cref="WorkerEnabled"/> — явная настройка ВЛАДЕЛЬЦА фоновой обработки.
/// </para>
/// <para>
/// Штатный запуск приложения — это <c>Chernika.Web</c> (см. <c>start_app.cmd</c>).
/// Обработчик сроков <b>обязан жить в нём</b>: настройки <c>WarningDays</c>,
/// <c>ReviewTaskDueDays</c> и <c>RunOnStartup</c> сами по себе ничего не
/// запускают — их исполняет только зарегистрированный worker.
/// </para>
/// <para>
/// Второй владелец недопустим. Если запустить <c>Chernika.Web</c> и
/// <c>Chernika.Api</c> одновременно, обработка выполнится дважды, а это
/// дубли уведомлений, лишние аудит-записи и вдвое больше нагрузки. Владелец
/// поэтому задаётся данными, а не фактом подключения: в
/// <c>Chernika.Web/appsettings.json</c> стоит <c>true</c>, в
/// <c>Chernika.Api/appsettings.json</c> — <c>false</c>. Регистрация проверяема
/// тестом, а не догадкой.
/// </para>
/// </summary>
public sealed class HKExpirationOptions
{
    /// <summary>
    /// Запускать ли worker в ЭТОМ хосте. По умолчанию <c>false</c>: отсутствие
    /// явного решения не должно означать, что обработка идёт в обоих хостах.
    /// </summary>
    public bool WorkerEnabled { get; set; }

    /// <summary>
    /// Пороги предупреждения в днях до окончания срока.
    /// <para>
    /// По умолчанию пусто, и это НЕ опечатка. Привязка конфигурации к массиву
    /// со значением по умолчанию не заменяет его, а ДОПИСЫВАЕТ: с
    /// <c>new[] { 90, 30, 7 }</c> в свойстве раздел <c>WarningDays: [90,30,7]</c>
    /// давал бы <c>[90,30,7,90,30,7]</c> — и так в обоих хостах, молча и при
    /// каждом запуске. Источник значений по умолчанию — appsettings.json, где
    /// они и видны; пустой массив означает «порогов нет», и обработка тогда
    /// ничего не присылает.
    /// </para>
    /// </summary>
    public int[] WarningDays { get; set; } = Array.Empty<int>();

    /// <summary>Время ежедневного запуска в UTC, формат <c>HH:mm</c>.</summary>
    public string DailyRunTimeUtc { get; set; } = "01:00";

    /// <summary>
    /// Срок задачи «Пересмотр ХК» в днях от момента создания. Фактический срок
    /// ограничивается днём окончания действия карты: срок позже автоархивации
    /// бессмыслен, задачу отменят, не дав её выполнить.
    /// </summary>
    public int ReviewTaskDueDays { get; set; } = 14;

    /// <summary>Выполнить прогон сразу при старте хоста.</summary>
    public bool RunOnStartup { get; set; } = true;
}