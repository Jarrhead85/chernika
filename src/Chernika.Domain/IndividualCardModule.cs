namespace Chernika.Domain;

/// <summary>
/// Настройка законсервированного модуля индивидуальных карт (ИК).
/// <para>
/// По решению владельца ИК выведены из действующего функционала проекта.
/// Код, сущности, таблицы, миграции и исторические данные сохранены целиком и
/// не удаляются: модуль должен быть возобновляем без потери наработок.
/// </para>
/// <para>
/// По умолчанию модуль ВЫКЛЮЧЕН во всех средах, включая Development: операции
/// создания, пересчёта и изменения ИК отклоняются на сервере до обращения к БД.
/// Включение — только явной настройкой раздела <c>IndividualCards</c>
/// (<c>Enabled=true</c>); тесты включают его осознанно, чтобы сохранённый код и
/// его покрытие оставались рабочими.
/// </para>
/// </summary>
public sealed class IndividualCardModuleOptions
{
    /// <summary>
    /// Разрешены ли операции записи по ИК. <c>false</c> — штатный режим
    /// законсервированного модуля: контролируемый отказ без записи в БД.
    /// </summary>
    public bool Enabled { get; set; }
}

/// <summary>
/// Граница модуля ИК: единственное место, где решается, разрешена ли операция.
/// </summary>
public interface IIndividualCardModuleState
{
    /// <summary>Разрешены ли операции записи по ИК.</summary>
    bool IsEnabled { get; }
}
