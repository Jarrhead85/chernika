namespace Chernika.Domain.Enums;

/// <summary>
/// Состояние одного этапа согласования карты.
/// <para>
/// Отдельное перечисление, а не <see cref="HKCardStatus"/>: общий статус карты —
/// отображение рабочего жизненного цикла целиком и не выражает состояние
/// отдельной части. Переиспользование общего статуса для этапа сделало бы
/// невозможным, например, принятые реквизиты при возвращённом составе.
/// </para>
/// <para>
/// Состояния повторяют рабочие состояния прежнего процесса, но принадлежат
/// этапу: <c>Draft</c>, <c>OnReview</c>, <c>RevisionRequired</c>, <c>Approved</c>.
/// </para>
/// </summary>
public enum HKApprovalStageState
{
    /// <summary>
    /// Этап не отправлен: автор заполняет или ждёт отправки.
    /// </summary>
    Draft = 0,

    /// <summary>
    /// Этап отправлен и находится у назначенного согласующего.
    /// </summary>
    OnReview = 1,

    /// <summary>
    /// Согласующий вернул этап на доработку.
    /// </summary>
    RevisionRequired = 2,

    /// <summary>
    /// Этап принят. Дата принятия фиксируется один раз и не переписывается.
    /// </summary>
    Approved = 3
}