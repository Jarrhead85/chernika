namespace Chernika.Domain.Enums;

/// <summary>
/// Подтверждение, что прежние поля <c>GsmMaterial.Gost</c>/<c>Description</c>
/// остаются источником истины, а значит однонаправленная сверка
/// <c>Gost → Nd</c> ещё допустима.
/// <para>
/// Существует ровно один член и он удаляется в **PR-3 вместе с самым методом
/// сверки**. Это сделано намеренно вместо булева флага: удаление члена превращает
/// все вызовы в ошибки компиляции, поэтому после переключения штатного
/// редактирования на <c>Nd</c>/<c>IntendedUse</c> запустить старую сверку,
/// затирающую новые значения, уже невозможно — молча и без ошибок времени
/// выполнения.
/// </para>
/// </summary>
public enum GsmLegacySourceOfTruth
{
    /// <summary>Источник истины — прежние поля; <c>Nd</c>/<c>IntendedUse</c> подлежат приведению к ним.</summary>
    LegacyGostIsSourceOfTruth = 0
}
