namespace Chernika.Domain.Enums;

/// <summary>
/// Этап согласования химмотологической карты.
/// <para>
/// Автономная карта согласуется в два независимых этапа. Этапы хранятся и
/// переключаются по отдельности: принятие реквизитов не означает согласованный
/// состав, а возврат состава не отменяет принятые реквизиты.
/// </para>
/// </summary>
public enum HKApprovalStage
{
    /// <summary>
    /// Согласование реквизитов и основания ХК.
    /// Первый этап: назначение, цель, нормативная база, обращение, даты, PDF.
    /// </summary>
    Details = 1,

    /// <summary>
    /// Согласование состава и норм ХК.
    /// Второй этап: позиции собственного дерева, конечные строки и материалы.
    /// </summary>
    Composition = 2
}